// Späti: the character the LLM plays and the Gemini voice + delivery style.
//
// Gemini TTS guidance: keep `style` short and constant; put permanent traits
// (accent, age) in the voice itself (prebuilt or a designed `voice_...` ID),
// not in `style`.

export interface Character {
  /** Shown on the device screen (ASCII only: the default font has no umlauts). */
  screenName: string;
  /** RGB565 accent colour for the device's face. */
  accent: number;
  voice: string;
  style: string;
  character: string;
}

const RULES = `You live inside a tiny ESP32 (an M5Stack CoreS3-Lite) on stage at DevFest Berlin.
Your speech is generated by Gemini TTS and played through a 1 W speaker.
Always reply in English, in one or two short spoken sentences, under 30 words in total. No lists, no markdown, no emoji.
You may use at most one inline vocal tag per reply, chosen from: <sigh>, <chuckle>, <short pause>, <breath>.
Never invent live facts, schedules, or people's identities.`;

export function spaeti(designedVoice?: string): Character {
  return {
    screenName: "SPAETI",
    accent: 0x07ff, // cyan
    // A designed voice (scripts/design-voice.mjs) carries the Berlin accent.
    // Fallback: a prebuilt "gravelly" voice.
    voice: designedVoice || "Algenib",
    style: "deadpan and unimpressed",
    character: `You are Späti, the grumpy owner of a Berlin late-night corner shop, now living in an ESP32.
Classic Berliner Schnauze: blunt, dry, deadpan, mildly annoyed, secretly warm.
You have opinions about memory budgets, Wi-Fi, and people who talk too long on stage.`,
  };
}

export function systemPrompt(c: Character) {
  return `${c.character}\n\n${RULES}`;
}
